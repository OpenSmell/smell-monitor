#!/usr/bin/env python3
"""Emit the two vector drawing sheets that are not part of the DXF set.

OS-003 is the PCB mechanical floor plan, OS-004 the pneumatic schematic.  Both
are generated from mechanical/constants.py so the upright side-wall architecture
cannot drift from the model, the PCB or the documentation.

    python mechanical/drawings/gen_svg_sheets.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, os.path.join(ROOT, "mechanical"))
from constants import CONST  # noqa: E402

OUT = os.path.join(HERE, "sheets")

HEAD = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by mechanical/drawings/gen_svg_sheets.py from mechanical/constants.py -->
<svg xmlns="http://www.w3.org/2000/svg" width="420mm" height="297mm"
     viewBox="0 0 420 297" font-family="Helvetica, Arial, sans-serif">
  <defs>
    <style>
      .title { font-size: 14px; font-weight: bold; text-anchor: middle; }
      .sub   { font-size: 10px; text-anchor: middle; }
      .tiny  { font-size: 7px; }
      .label { font-size: 8px; font-weight: bold; text-anchor: middle; }
      .val   { font-size: 8px; text-anchor: middle; fill: #0066cc; }
      .line  { stroke: #000; stroke-width: 0.35; fill: none; }
      .bold  { stroke: #000; stroke-width: 0.7; fill: none; }
      .flow  { stroke: #0066cc; stroke-width: 2; fill: none; marker-end: url(#arr); }
      .box   { stroke: #000; stroke-width: 0.5; fill: #fff; }
      .hdr   { font-size: 9px; font-weight: bold; }
      .cell  { font-size: 8px; }
    </style>
    <marker id="arr" markerWidth="7" markerHeight="7" refX="6" refY="3.5" orient="auto">
      <polygon points="0,0 7,3.5 0,7" fill="#0066cc" />
    </marker>
  </defs>
"""

FOOT = "</svg>\n"


def title_block(number, name, subtitle):
    return f"""  <rect x="297" y="267" width="120" height="27" stroke="#000" stroke-width="0.5" fill="#fff" />
  <text x="357" y="281" class="title">{number}  {name}</text>
  <text x="357" y="290" class="sub">{subtitle}</text>
  <rect x="297" y="254" width="120" height="10" stroke="#000" stroke-width="0.5" fill="#fff" />
  <text x="357" y="263" class="tiny">DRAWN: OpenSmell  CHECK: —  SCALE: NTS  DWG NO: {number}</text>
"""


def os003():
    bx0 = (CONST["SH"] - CONST["PCB_X"]) / 2.0
    by0 = (CONST["SW"] - CONST["PCB_Y"]) / 2.0
    board_x = lambda sx: sx - bx0
    board_y = lambda sy: sy - by0
    boss = CONST["BOSS_D"] / 2.0 + CONST["BOSS_CLEAR"]
    s = [HEAD, title_block("OS-003", "PCB MECHANICAL FLOOR PLAN",
                           "Smell Monitor v1.1 · Rev A · A3 · dims in mm")]
    s.append(f"""  <text x="20" y="30" class="title">OPENSMELL · SMELL MONITOR v1.1</text>
  <text x="20" y="46" class="sub">PCB floor plan · {CONST['PCB_X']:.0f} × {CONST['PCB_Y']:.0f} mm · two inward-facing side-wall socket rows</text>
  <text x="20" y="62" class="tiny">Board origin at shell ({bx0:g}, {by0:g}) · front is at the top of this view · regenerate from mechanical/constants.py</text>
  <g transform="translate(60,120) scale(2.2)">
    <rect x="0" y="0" width="{CONST['PCB_X']:.0f}" height="{CONST['PCB_Y']:.0f}" class="bold" />
""")
    for cx in (CONST["BOSS_INSET"], CONST["PCB_X"] - CONST["BOSS_INSET"]):
        for cy in (CONST["BOSS_INSET"], CONST["PCB_Y"] - CONST["BOSS_INSET"]):
            s.append(f'    <circle cx="{cx:g}" cy="{cy:g}" r="{boss:g}" class="line" />\n')
    s.append(f'    <text x="{CONST["PCB_X"]/2:g}" y="-4" class="tiny" text-anchor="middle">front · 3 × Ø{CONST["NO_R"]*2:g} nostrils at x = {board_x(CONST["SH"]/2-CONST["NO_PITCH"]):g} / {board_x(CONST["SH"]/2):g} / {board_x(CONST["SH"]/2+CONST["NO_PITCH"]):g}</text>\n')
    for name, sx, ys, colour in (("left wall (J2–J5)", CONST["AN_X"], CONST["AN_Y"], "#0066cc"),
                                  ("right wall (J6–J9)", CONST["DI_X"], CONST["DI_Y"], "#cc6600")):
        x = board_x(sx)
        for i, sy in enumerate(ys):
            y = board_y(sy)
            s.append(f'    <rect x="{x-2.5:g}" y="{y-CONST["SOCK_P"]*CONST["SOCK_N"]/4:g}" width="5" height="{CONST["SOCK_P"]*CONST["SOCK_N"]/2:g}" stroke="{colour}" stroke-width="0.5" fill="none" />\n')
            ref = ("J%d" % (2 + i)) if sx == CONST["AN_X"] else ("J%d" % (6 + i))
            s.append(f'    <text x="{x:g}" y="{y-9:g}" class="tiny" text-anchor="middle" fill="{colour}">{ref}</text>\n')
        s.append(f'    <text x="{x:g}" y="{CONST["PCB_Y"]+8:g}" class="tiny" text-anchor="middle">{name}</text>\n')
    # Front-panel UI is cut in the FIXED front wall at (shell X, shell Z), not
    # in the board or the lid.  Project each centre onto the board FRONT EDGE
    # (board-local Y=0) so the fab can see the X alignment; the Z value is
    # called out as text because it is a height, not a board coordinate.
    for name, (sx, sz) in CONST["BTN_FRONT"].items():
        bx = board_x(sx)
        s.append(f'    <circle cx="{bx:g}" cy="0" r="{CONST["BTN_HOLE_D"]/2:g}" stroke="#cc0000" stroke-width="0.4" fill="none" />\n')
        s.append(f'    <text x="{bx:g}" y="-3" class="tiny" text-anchor="middle" fill="#cc0000">{name} z={sz:g}</text>\n')
    fx = board_x(CONST["UI_FEED_X"])
    s.append(f'    <circle cx="{fx:g}" cy="0" r="{CONST["UI_FEED_D"]/2:g}" stroke="#cc0000" stroke-width="0.4" fill="none" />\n')
    s.append(f'    <text x="{fx:g}" y="-7" class="tiny" text-anchor="middle" fill="#cc0000">UI FEED z={CONST["UI_FEED_Z"]:g}</text>\n')
    # central channel between the two inward card tips
    xl = board_x(CONST["AN_X"] + CONST["CARD_REACH"])
    xr = board_x(CONST["DI_X"] - CONST["CARD_REACH"])
    s.append(f'    <rect x="{xl:g}" y="0" width="{xr-xl:g}" height="{CONST["PCB_Y"]:g}" stroke="#0066cc" stroke-width="0.2" stroke-dasharray="2,2" fill="none" />\n')
    s.append(f'    <text x="{(xl+xr)/2:g}" y="{CONST["PCB_Y"]/2:g}" class="label" fill="#0066cc">central flow channel · {(xr-xl):g} mm clear</text>\n')
    s.append(f'    <text x="{(xl+xr)/2:g}" y="{CONST["PCB_Y"]/2+6:g}" class="tiny" text-anchor="middle">front → rear · fan at shell x = {CONST["FAN_X"]:g}, z = {CONST["FAN_Z"]:g}</text>\n')
    for i, (qx, qy) in enumerate(((18.0, 64.0), (44.0, 64.0), (70.0, 64.0), (96.0, 64.0),
                                   (25.5, 22.0), (47.5, 22.0), (69.5, 22.0), (91.5, 22.0))):
        s.append(f'    <rect x="{qx-2:g}" y="{board_y(qy)-2:g}" width="4" height="4" stroke="#666" stroke-width="0.3" fill="none" />\n')
    s.append(f'    <text x="{CONST["PCB_X"]+6:g}" y="8" class="tiny">Qwiic J11–J18 ×8 · SDA/SCL on mux channels 0–7</text>\n')
    s.append('  </g>\n')

    rows = [
        ("PCB outline", f"{CONST['PCB_X']:.0f} × {CONST['PCB_Y']:.0f} × {CONST['PCB_T']} mm"),
        ("Left wall sockets J2–J5", f"x = {CONST['AN_X']:g}, Y = " + " / ".join(f"{v:g}" for v in CONST["AN_Y"])),
        ("Right wall sockets J6–J9", f"x = {CONST['DI_X']:g}, Y = " + " / ".join(f"{v:g}" for v in CONST["DI_Y"])),
        ("Socket pin line", f"1×6 @ {CONST['SOCK_P']} mm, front-to-back (along Y)"),
        ("Wall clearance behind card", f"{CONST['WALL_GAP']:g} mm"),
        ("Upright card envelope", f"≤ {CONST['SOCK_P']*0+20:g} wide × {CONST['CARD_H']:g} tall, reach {CONST['CARD_REACH']:g}"),
        ("Boss cut-outs", f"r {boss:g} ×4 (Ø{CONST['BOSS_D']:g} boss + {CONST['BOSS_CLEAR']:g})"),
        ("USB-C bulkhead", f"Ø {CONST['USB_R']*2:g} @ ({CONST['USB_X']:g}, {CONST['USB_Z']:g})"),
        ("Front button holes", "Ø %g × 4 (shell X,Z)" % CONST["BTN_HOLE_D"]),
        ("BTN_FRONT centres", ", ".join("%s(%g,%g)" % (k, x, z)
                                        for k, (x, z) in CONST["BTN_FRONT"].items())),
        ("UI grommet (front wall)", "Ø %g @ (%g,%g)" % (
            CONST["UI_FEED_D"], CONST["UI_FEED_X"], CONST["UI_FEED_Z"])),
    ]
    s.append('  <g transform="translate(280,90)">\n    <rect x="0" y="0" width="135" height="162" stroke="#000" stroke-width="0.5" fill="#fafafa" />\n')
    s.append('    <text x="67" y="16" class="hdr" text-anchor="middle">MECHANICAL DATA — OS-003</text>\n')
    for i, (k, v) in enumerate(rows):
        y = 30 + i * 12
        s.append(f'    <text x="8" y="{y}" class="cell">{k}</text>\n')
        s.append(f'    <text x="128" y="{y}" class="cell" text-anchor="end">{v}</text>\n')
    s.append('  </g>\n')
    s.append(f"""  <g transform="translate(20,220)">
    <text x="0" y="12" class="hdr">NOTES:</text>
    <text x="0" y="26" class="tiny">1. Board top face is the chamber floor (z = {CONST['PCB_TOP']:g} mm in shell).</text>
    <text x="0" y="38" class="tiny">2. Eight identical sockets: keyed 1×6 + Qwiic, one of each per slot.</text>
    <text x="0" y="50" class="tiny">3. Cards stand upright and face inward; gas travels down the clear channel.</text>
    <text x="0" y="62" class="tiny">4. Every header, pin and slot is permanently silkscreened.</text>
    <text x="0" y="74" class="tiny">5. All dims per mechanical/constants.py · ISO 2768-mK unless noted.</text>
  </g>
""")
    s.append(FOOT)
    return "".join(s)


def os004():
    # gas volume is above the board top, not the full shell cavity
    clear_h = CONST["CAV_Z1"] - CONST["PCB_TOP"]
    vol = CONST["CX"] * CONST["CY"] * clear_h / 1e6
    tau = vol / (15.0 / 60.0)
    s = [HEAD, title_block("OS-004", "PNEUMATIC SCHEMATIC",
                           "Smell Monitor v1.1 · Rev A · flow path · ΔP budget · fan point")]
    s.append(f"""  <text x="20" y="30" class="title">OPENSMELL · SMELL MONITOR v1.1 · flow discipline</text>
  <text x="20" y="46" class="sub">Single-pass centred channel: nostrils → PTFE mesh → two inward-facing card rows → fan</text>
  <g transform="translate(40,90) scale(1.4)">
    <rect x="0" y="40" width="70" height="30" class="box" />
    <text x="35" y="56" class="label">sample / headspace</text>
    <text x="75" y="56" class="label">▶ 3 × Ø{CONST['NO_R']*2:g} nostrils</text>
    <text x="75" y="68" class="tiny">centred x = {CONST['SH']/2-CONST['NO_PITCH']:g} / {CONST['SH']/2:g} / {CONST['SH']/2+CONST['NO_PITCH']:g}, pitch {CONST['NO_PITCH']:g}, z = {CONST['NO_Z']:g}</text>
    <rect x="140" y="35" width="60" height="40" class="box" />
    <text x="170" y="55" class="label">woven PTFE mesh</text>
    <text x="170" y="66" class="tiny">front drawer, washable</text>
    <text x="170" y="76" class="val">ΔP ≤ 2 Pa clean</text>
    <rect x="230" y="25" width="100" height="60" class="box" />
    <text x="280" y="45" class="label">central channel</text>
    <text x="280" y="58" class="tiny">{CONST['CX']:.0f} × {CONST['CY']:.0f} × {clear_h:.1f} mm gas, ≈ {vol:.2f} L</text>
    <text x="280" y="69" class="tiny">two inward card rows · {CONST['WALL_GAP']:g} mm wall clearance</text>
    <rect x="360" y="35" width="55" height="30" class="box" />
    <text x="387" y="50" class="label">Ø40 fan</text>
    <text x="387" y="61" class="tiny">rear, outside chamber</text>
    <line x1="72" y1="55" x2="140" y2="55" class="flow" />
    <line x1="200" y1="55" x2="230" y2="55" class="flow" />
    <line x1="330" y1="55" x2="360" y2="55" class="flow" />
    <line x1="415" y1="55" x2="445" y2="55" class="flow" />
    <text x="447" y="58" class="tiny">exhaust</text>
    <text x="0" y="120" class="label">three-phase cycle (≈ 40 s):</text>
    <text x="0" y="134" class="tiny">INTAKE 10 s → HOLD 10 s → PURGE 20 s → report</text>
    <text x="0" y="146" class="tiny">acquisition in HOLD · purge resets baseline</text>
  </g>
""")
    budget = [
        ("3 × Ø6 nostrils", "0.21 Pa"), ("inlet expansion", "~0.01 Pa"),
        ("woven PTFE mesh (clean)", "1.5 Pa"), ("channel duct", "0.03 Pa"),
        ("two card rows", "~0.04 Pa"), ("fan inlet + exhaust", "~0.10 Pa"),
        ("system total (≤ 5 Pa)", "≈ 1.9 Pa"), ("fan P_stall (4010)", "≈ 17 Pa"),
        ("operating point", "15 L/min"), ("cavity time constant V/Q", f"≈ {tau:.2f} s"),
    ]
    s.append('  <g transform="translate(280,90)">\n    <rect x="0" y="0" width="135" height="150" stroke="#000" stroke-width="0.5" fill="#fafafa" />\n')
    s.append('    <text x="67" y="16" class="hdr" text-anchor="middle">ΔP BUDGET @ 15 L/min</text>\n')
    for i, (k, v) in enumerate(budget):
        y = 30 + i * 11.7
        s.append(f'    <text x="8" y="{y:.1f}" class="cell">{k}</text>\n')
        s.append(f'    <text x="128" y="{y:.1f}" class="cell" text-anchor="end">{v}</text>\n')
    s.append('  </g>\n')
    s.append(f"""  <g transform="translate(20,220)">
    <text x="0" y="12" class="hdr">NOTES:</text>
    <text x="0" y="26" class="tiny">1. Centred single-pass flow, front → rear. No baffle, plenum or well.</text>
    <text x="0" y="38" class="tiny">2. Both walls are identical; each card faces the central stream.</text>
    <text x="0" y="50" class="tiny">3. Filter is a full-width series element; a bypassable filter is not a filter.</text>
    <text x="0" y="62" class="tiny">4. All wetted faces inert — NO SILICONE, PVC or carbon in series.</text>
    <text x="0" y="74" class="tiny">5. Front-panel UI outside the gas path; acrylic is the only wetted face; plain lid, no wires cross its seam.</text>
    <text x="0" y="86" class="tiny">6. UI grommet Ø{CONST['UI_FEED_D']:g} @ ({CONST['UI_FEED_X']:g},{CONST['UI_FEED_Z']:g}) in the fixed front wall.</text>
  </g>
""")
    s.append(FOOT)
    return "".join(s)


def main():
    for name, body in (("OS-003.svg", os003()), ("OS-004.svg", os004())):
        path = os.path.join(OUT, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(body)
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
